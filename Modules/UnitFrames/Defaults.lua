local function BuildIndicators(base, overrides)
    if not overrides then return base end
    for key, patch in pairs(overrides) do
        if type(patch) == "table" then
            base[key] = base[key] or {}
            for k, v in pairs(patch) do
                base[key][k] = v
            end
        else
            base[key] = base[key] or {}
            base[key].enabled = patch
        end
    end
    return base
end

